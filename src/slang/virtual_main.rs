/// The shader stage for a virtual entry point.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Stage {
    Compute,
    Vertex,
    Fragment,
}

impl Stage {
    fn shader_attr(self) -> &'static str {
        match self {
            Stage::Compute => r#"[shader("compute")]"#,
            Stage::Vertex => r#"[shader("vertex")]"#,
            Stage::Fragment => r#"[shader("fragment")]"#,
        }
    }
}

