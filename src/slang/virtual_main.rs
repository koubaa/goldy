/// Extract the inner element type name for each bindless slot from the
/// `[goldy_*]` entry points in `source`.
///
/// For `Scattered<T>` / `BufRO<T>` → `Some("T")`, for `ByteAddress` →
/// `None`, for broadcasts → `Some(struct_name)`, for textures/samplers/SVs
/// → `None`.  Fragment entries take precedence, matching [`extract_push_constant_categories`].
pub fn extract_binding_element_type_names(source: &str) -> Vec<Option<String>> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Vec::new();
    }

    fn type_name_for_param(param: &Param) -> Option<String> {
        match &param.kind {
            ParamKind::Resource => {
                let ty = param.ty.trim();
                fn inner(ty: &str, prefix: &str) -> Option<String> {
                    if ty.starts_with(prefix) && ty.ends_with('>') {
                        Some(ty[prefix.len()..ty.len() - 1].to_string())
                    } else {
                        None
                    }
                }
                inner(ty, "Scattered<")
                    .or_else(|| inner(ty, "BufRO<"))
                    .or_else(|| inner(ty, "Interpolated<"))
                    .or_else(|| inner(ty, "DirectSpatial<"))
            }
            ParamKind::Broadcast => Some(param.ty.clone()),
            _ => None,
        }
    }

    fn extract_from_params(params: &[ParamItem]) -> Vec<Option<String>> {
        let mut names: Vec<Option<String>> = Vec::new();
        for item in params {
            match item {
                ParamItem::Single(p) => {
                    if matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast) {
                        names.push(type_name_for_param(p));
                    }
                }
                ParamItem::Conditional {
                    then_params,
                    else_params,
                    ..
                } => {
                    let then_count = then_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let else_count = else_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let max_slots = then_count.max(else_count);
                    for i in 0..max_slots {
                        let then_name = then_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(type_name_for_param);
                        let else_name = else_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(type_name_for_param);
                        if then_name == else_name {
                            names.push(then_name);
                        } else {
                            names.push(None);
                        }
                    }
                }
            }
        }
        names
    }

    let mut fragment_names: Option<Vec<Option<String>>> = None;
    let mut fallback_names: Option<Vec<Option<String>>> = None;

    for entry in &entries {
        let names = extract_from_params(&entry.params);
        if !names.is_empty() {
            if entry.stage == Stage::Fragment {
                fragment_names = Some(names);
            } else if fallback_names.is_none() || entry.stage == Stage::Compute {
                fallback_names = Some(names);
            }
        }
    }

    fragment_names.or(fallback_names).unwrap_or_default()
}

/// Extract per-bindless-slot [`ResourceCategory`](crate::types::ResourceCategory) expectations from the
/// `[goldy_*]` entry points in `source`.
///
/// Returns a vector indexed by bindless slot. Each element is `Some(category)`
/// when the slot's type is unambiguous, or `None` when the source has no
/// `[goldy_*]` annotations.  Multiple entry points (vertex + fragment) are
/// merged: fragment takes precedence for shared slots.
pub fn extract_push_constant_categories(source: &str) -> Vec<Option<crate::types::ResourceCategory>> {
    use crate::types::ResourceCategory;

    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Vec::new();
    }

    fn category_for_param(param: &Param) -> Option<ResourceCategory> {
        match &param.kind {
            ParamKind::Resource => {
                let ty = param.ty.trim();
                if ty.starts_with("Scattered<") || ty.starts_with("BufRO<") || ty == "ByteAddress" {
                    Some(ResourceCategory::Scattered)
                } else if ty.starts_with("Interpolated<") {
                    Some(ResourceCategory::Texture)
                } else if ty.starts_with("DirectSpatial<") {
                    Some(ResourceCategory::StorageImage)
                } else if ty == "Filter" {
                    Some(ResourceCategory::Sampler)
                } else if ty == "Accel" {
                    Some(ResourceCategory::Accel)
                } else {
                    None
                }
            }
            ParamKind::Broadcast => Some(ResourceCategory::Broadcast),
            _ => None,
        }
    }

    fn extract_from_params(params: &[ParamItem]) -> Vec<Option<ResourceCategory>> {
        let mut cats: Vec<Option<ResourceCategory>> = Vec::new();
        for item in params {
            match item {
                ParamItem::Single(p) => {
                    if matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast) {
                        cats.push(category_for_param(p));
                    }
                }
                ParamItem::Conditional {
                    then_params,
                    else_params,
                    ..
                } => {
                    let then_count = then_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let else_count = else_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let max_slots = then_count.max(else_count);
                    for i in 0..max_slots {
                        let then_cat = then_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(category_for_param);
                        let else_cat = else_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(category_for_param);
                        if then_cat == else_cat {
                            cats.push(then_cat);
                        } else {
                            cats.push(None);
                        }
                    }
                }
            }
        }
        cats
    }

    // Fragment shader expectations take precedence (resource binding typically lives there).
    let mut fragment_cats: Option<Vec<Option<ResourceCategory>>> = None;
    let mut fallback_cats: Option<Vec<Option<ResourceCategory>>> = None;

    for entry in &entries {
        let cats = extract_from_params(&entry.params);
        if !cats.is_empty() {
            if entry.stage == Stage::Fragment {
                fragment_cats = Some(cats);
            } else if fallback_cats.is_none() || entry.stage == Stage::Compute {
                fallback_cats = Some(cats);
            }
        }
    }

    fragment_cats.or(fallback_cats).unwrap_or_default()
}

/// Extract per-slot DX12 bindless view expectations (`UAV` vs `SRV`) from `[goldy_*]` entry points.
///
/// Merging rules match [`extract_push_constant_categories`].
#[cfg(all(feature = "dx12", target_os = "windows"))]
pub(crate) fn extract_push_constant_slot_kinds(source: &str) -> Vec<Option<crate::types::BindlessSlotKind>> {
    use crate::types::BindlessSlotKind;

    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Vec::new();
    }

    fn slot_kind_for_param(param: &Param) -> Option<BindlessSlotKind> {
        match &param.kind {
            ParamKind::Resource => {
                let ty = param.ty.trim();
                if ty.starts_with("Scattered<") || ty == "ByteAddress" {
                    Some(BindlessSlotKind::StorageUav)
                } else if ty.starts_with("BufRO<") || ty == "Accel" {
                    Some(BindlessSlotKind::ReadOnlySrv)
                } else {
                    None
                }
            }
            ParamKind::Broadcast => Some(BindlessSlotKind::UniformCbv),
            _ => None,
        }
    }

    fn extract_from_params(params: &[ParamItem]) -> Vec<Option<BindlessSlotKind>> {
        let mut kinds: Vec<Option<BindlessSlotKind>> = Vec::new();
        for item in params {
            match item {
                ParamItem::Single(p) => {
                    if matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast) {
                        kinds.push(slot_kind_for_param(p));
                    }
                }
                ParamItem::Conditional {
                    then_params,
                    else_params,
                    ..
                } => {
                    let then_count = then_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let else_count = else_params
                        .iter()
                        .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                        .count();
                    let max_slots = then_count.max(else_count);
                    for i in 0..max_slots {
                        let then_kind = then_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(slot_kind_for_param);
                        let else_kind = else_params
                            .iter()
                            .filter(|p| matches!(p.kind, ParamKind::Resource | ParamKind::Broadcast))
                            .nth(i)
                            .and_then(slot_kind_for_param);
                        if then_kind == else_kind {
                            kinds.push(then_kind);
                        } else {
                            kinds.push(None);
                        }
                    }
                }
            }
        }
        kinds
    }

    let mut fragment_kinds: Option<Vec<Option<BindlessSlotKind>>> = None;
    let mut fallback_kinds: Option<Vec<Option<BindlessSlotKind>>> = None;

    for entry in &entries {
        let kinds = extract_from_params(&entry.params);
        if !kinds.is_empty() {
            if entry.stage == Stage::Fragment {
                fragment_kinds = Some(kinds);
            } else if fallback_kinds.is_none() || entry.stage == Stage::Compute {
                fallback_kinds = Some(kinds);
            }
        }
    }

    fragment_kinds.or(fallback_kinds).unwrap_or_default()
}

/// Transform a Slang source string that may contain `[goldy_*]` virtual entry
/// points into a standard Slang source with generated `[shader(...)]` wrappers.
///
/// If no `[goldy_*]` attributes are present, the source is returned unchanged.
pub fn transform_virtual_main(source: &str) -> String {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return source.to_string();
    }

    // Generate wrapper code (in declaration order — first entry first).
    let mut wrapper_block = String::from("// [generated by goldy virtual_main — do not edit]\n");
    for entry in &entries {
        wrapper_block.push_str(&emit_wrapper(entry));
        wrapper_block.push_str("\n\n");
    }

    // Modify the original source (remove [goldy_*] attrs, rename fns).
    // Process in *reverse* position order so earlier byte offsets stay valid.
    let mut modified = source.to_string();
    for entry in entries.iter().rev() {
        apply_entry_transforms(&mut modified, entry);
    }

    // Reset Slang's line counter to 1 so that diagnostics for the user's code
    // are reported at the original source lines, not offset by the generated prefix.
    wrapper_block + "#line 1\n" + &modified
}

/// Transform `[goldy_compute]` sources for Slang host-callable CPU JIT.
///
/// Unlike [`transform_virtual_main`], resources stay typed `uniform` entry-point
/// parameters (pointer + count on CPU) instead of Goldy bindless slot indices.
/// Graphics stages, textures, samplers, byte-address buffers, and broadcast
/// structs are rejected — they do not lower on this debug path yet.
pub fn transform_virtual_main_cpu(source: &str) -> Result<String, String> {
    let has_compute = source.contains("[goldy_compute]");
    let has_graphics = source.contains("[goldy_vertex]") || source.contains("[goldy_fragment]");
    if has_graphics {
        return Err("CPU host-callable debug path supports [goldy_compute] only (no vertex/fragment)".into());
    }
    if !has_compute {
        return Ok(source.to_string());
    }

    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(source.to_string());
    }
    for entry in &entries {
        if entry.stage != Stage::Compute {
            return Err(format!("CPU host-callable: entry `{}` is not compute", entry.fn_name));
        }
        cpu_check_entry(entry)?;
    }

    let mut wrapper_block = String::from("// [generated by goldy virtual_main CPU — do not edit]\n");
    for entry in &entries {
        wrapper_block.push_str(&emit_cpu_wrapper(entry));
        wrapper_block.push_str("\n\n");
    }

    let mut modified = source.to_string();
    for entry in entries.iter().rev() {
        apply_entry_transforms(&mut modified, entry);
    }

    Ok(wrapper_block + "#line 1\n" + &modified)
}

fn cpu_check_entry(entry: &EntryDef) -> Result<(), String> {
    for item in &entry.params {
        match item {
            ParamItem::Conditional { .. } => {
                return Err("CPU host-callable: preprocessor-conditional parameters are not supported".into());
            }
            ParamItem::Single(param) => cpu_check_param(param)?,
        }
    }
    Ok(())
}

fn cpu_check_param(param: &Param) -> Result<(), String> {
    match &param.kind {
        ParamKind::Scalar => Ok(()),
        ParamKind::SystemValue(sv) => match sv {
            SvKind::DispatchThreadId | SvKind::GroupThreadId | SvKind::GroupId => Ok(()),
            other => Err(format!(
                "CPU host-callable: system value {:?} is not supported (`{}`)",
                other, param.name
            )),
        },
        ParamKind::Resource => {
            let ty = param.ty.trim();
            if ty.starts_with("Scattered<") || ty.starts_with("BufRO<") {
                Ok(())
            } else {
                Err(format!(
                    "CPU host-callable: resource type `{}` on `{}` does not lower (buffers only: BufRO / Scattered)",
                    param.ty, param.name
                ))
            }
        }
        ParamKind::Broadcast => Err(format!(
            "CPU host-callable: broadcast / constant-buffer param `{}` (`{}`) does not lower yet",
            param.name, param.ty
        )),
        ParamKind::PassThrough => Err(format!(
            "CPU host-callable: pass-through param `{}` is not supported",
            param.name
        )),
    }
}

/// Emit a CPU wrapper: typed `uniform` buffers/scalars + SV_* system values.
fn emit_cpu_wrapper(entry: &EntryDef) -> String {
    let mut out = String::new();
    out.push_str(entry.stage.shader_attr());
    out.push('\n');
    if let Some((x, y, z)) = entry.numthreads {
        out.push_str(&format!("[numthreads({}, {}, {})]\n", x, y, z));
    }

    let user_fn_name = format!("_goldy_user_{}", entry.fn_name);
    let mut sig = String::new();
    let mut body = String::new();
    let mut call = String::new();
    let mut sig_sep = false;
    let mut call_sep = false;
    let mut sv_idx = 0u32;

    let push_sig = |s: &str, sig: &mut String, sig_sep: &mut bool| {
        if *sig_sep {
            sig.push_str(", ");
        }
        sig.push_str(s);
        *sig_sep = true;
    };
    let push_call = |s: &str, call: &mut String, call_sep: &mut bool| {
        if *call_sep {
            call.push_str(", ");
        }
        call.push_str(s);
        *call_sep = true;
    };

    for item in &entry.params {
        let ParamItem::Single(param) = item else {
            continue;
        };
        match &param.kind {
            ParamKind::Resource | ParamKind::Scalar => {
                push_sig(&format!("uniform {} {}", param.ty, param.name), &mut sig, &mut sig_sep);
                push_call(&param.name, &mut call, &mut call_sep);
            }
            ParamKind::SystemValue(sv) => {
                let gn = format!("_sv{}", sv_idx);
                sv_idx += 1;
                push_sig(
                    &format!("{} {} : {}", sv.primitive(), gn, sv.semantic()),
                    &mut sig,
                    &mut sig_sep,
                );
                body.push_str(&format!("    {} {} = {}({});\n", param.ty, param.name, param.ty, gn));
                push_call(&param.name, &mut call, &mut call_sep);
            }
            ParamKind::Broadcast | ParamKind::PassThrough => {}
        }
    }

    out.push_str(&format!("{} {}({}) {{\n", entry.return_type, entry.fn_name, sig));
    out.push_str(&body);
    out.push_str(&format!("    {}({});\n", user_fn_name, call));
    out.push('}');
    out
}

/// How a `[goldy_compute]` resource parameter is bound on the WebGPU prototype.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum WgpuComputeResourceKind {
    /// `Scattered` / `ByteAddress` → storage buffer (read-write).
    StorageReadWrite,
    /// `BufRO` → storage buffer (read-only).
    StorageRead,
    /// Broadcast struct → uniform buffer.
    Uniform,
    /// `Interpolated<T>` → sampled texture.
    SampledTexture,
    /// `DirectSpatial<T>` → storage texture.
    StorageTexture,
    /// `Filter` → sampler.
    Sampler,
    /// `Accel` → acceleration structure (experimental ray query).
    AccelerationStructure,
}

impl WgpuComputeResourceKind {
    /// Default scheme slot access for this binding kind.
    pub fn default_access(self) -> crate::types::ResourceAccess {
        match self {
            Self::StorageReadWrite | Self::StorageTexture => crate::types::ResourceAccess::ReadWrite,
            Self::StorageRead | Self::Uniform | Self::SampledTexture | Self::Sampler | Self::AccelerationStructure => {
                crate::types::ResourceAccess::Read
            }
        }
    }
}

/// Portable compute binding layout for the WebGPU prototype.
///
/// `resources` is `None` when the source has no `[goldy_compute]` entries (raw WGSL
/// or unannotated Slang). The backend then treats every registry key as a storage
/// buffer. `scalar_count` is the number of `with_param` words packed into the
/// trailing uniform cbuffer.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct WgpuComputeLayout {
    pub resources: Option<Vec<WgpuComputeResourceKind>>,
    pub scalar_count: u32,
}

impl WgpuComputeLayout {
    /// Layout used for shaders that did not go through `[goldy_compute]` lowering.
    pub fn inferred_storage() -> Self {
        Self {
            resources: None,
            scalar_count: 0,
        }
    }

    /// Number of `BindResourcesRaw.indices` words a dispatch of this layout consumes.
    pub fn registry_index_count(&self) -> Option<usize> {
        self.resources.as_ref().map(|resources| resources.len())
    }

    /// Per-slot [`crate::types::ResourceAccess`] matching this layout (`BufRO` is Read).
    pub fn slot_access(&self) -> Vec<Option<crate::types::ResourceAccess>> {
        match &self.resources {
            None => Vec::new(),
            Some(kinds) => kinds.iter().copied().map(|kind| Some(kind.default_access())).collect(),
        }
    }
}

/// Reflect the WebGPU compute binding layout for `[goldy_compute]` source.
///
/// `#ifdef` parameter blocks are resolved against `defines` (must match the
/// defines passed to Slang for this shader variant, e.g. `msaa` / `msaa8`).
pub fn extract_webgpu_compute_layout(source: &str, defines: &[(&str, &str)]) -> Result<WgpuComputeLayout, String> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(WgpuComputeLayout::inferred_storage());
    }

    fn resource_kind(param: &Param) -> Result<WgpuComputeResourceKind, String> {
        let ty = param.ty.trim();
        if ty.starts_with("Scattered<") || ty == "ByteAddress" {
            Ok(WgpuComputeResourceKind::StorageReadWrite)
        } else if ty.starts_with("BufRO<") {
            Ok(WgpuComputeResourceKind::StorageRead)
        } else if ty.starts_with("Interpolated<") {
            Ok(WgpuComputeResourceKind::SampledTexture)
        } else if ty.starts_with("DirectSpatial<") {
            Ok(WgpuComputeResourceKind::StorageTexture)
        } else if ty == "Filter" {
            Ok(WgpuComputeResourceKind::Sampler)
        } else if ty == "Accel" {
            Ok(WgpuComputeResourceKind::AccelerationStructure)
        } else if matches!(param.kind, ParamKind::Broadcast) {
            Ok(WgpuComputeResourceKind::Uniform)
        } else {
            Err(format!("unsupported WebGPU resource parameter type `{ty}`"))
        }
    }

    let mut resources = Vec::new();
    let mut scalar_count = 0u32;
    let mut saw_compute = false;
    for entry in &entries {
        if entry.stage != Stage::Compute {
            continue;
        }
        saw_compute = true;
        resources.clear();
        scalar_count = 0;
        for param in resolve_cuda_params(&entry.params, defines) {
            match &param.kind {
                ParamKind::Resource | ParamKind::Broadcast => {
                    resources.push(resource_kind(&param)?);
                }
                ParamKind::Scalar => {
                    hlsl_scalar_from_uint_word(&param.ty, "_")?;
                    scalar_count += 1;
                }
                ParamKind::SystemValue(_) => {}
                ParamKind::PassThrough => {
                    return Err(format!(
                        "WebGPU compute entry has unsupported pass-through parameter `{}`",
                        param.name
                    ));
                }
            }
        }
    }
    if !saw_compute {
        return Err("WebGPU compute lowering found no [goldy_compute] entry point".to_string());
    }
    Ok(WgpuComputeLayout {
        resources: Some(resources),
        scalar_count,
    })
}

/// Reflect the WebGPU graphics binding layout for `[goldy_vertex]` / `[goldy_fragment]` source.
///
/// Bindings are assigned in vertex-then-fragment author order (same as the
/// graphics lowering). Shaders without those attributes use [`WgpuComputeLayout::inferred_storage`].
pub fn extract_webgpu_graphics_layout(source: &str) -> Result<WgpuComputeLayout, String> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(WgpuComputeLayout::inferred_storage());
    }

    fn resource_kind(param: &Param) -> Result<WgpuComputeResourceKind, String> {
        let ty = param.ty.trim();
        // Vertex/fragment storage is read-only: wgpu forbids writable storage in VS/FS
        // unless VERTEX_WRITABLE_STORAGE is enabled (native-only).
        if ty.starts_with("Scattered<") || ty == "ByteAddress" || ty.starts_with("BufRO<") {
            Ok(WgpuComputeResourceKind::StorageRead)
        } else if ty.starts_with("Interpolated<") {
            Ok(WgpuComputeResourceKind::SampledTexture)
        } else if ty.starts_with("DirectSpatial<") {
            Ok(WgpuComputeResourceKind::StorageTexture)
        } else if ty == "Filter" {
            Ok(WgpuComputeResourceKind::Sampler)
        } else if ty == "Accel" {
            Ok(WgpuComputeResourceKind::AccelerationStructure)
        } else if matches!(param.kind, ParamKind::Broadcast) {
            Ok(WgpuComputeResourceKind::Uniform)
        } else {
            Err(format!("unsupported WebGPU resource parameter type `{ty}`"))
        }
    }

    let mut resources = Vec::new();
    let mut scalar_count = 0u32;
    let mut saw_graphics = false;
    for stage in [Stage::Vertex, Stage::Fragment] {
        for entry in entries.iter().filter(|entry| entry.stage == stage) {
            saw_graphics = true;
            for item in &entry.params {
                let ParamItem::Single(param) = item else {
                    return Err("conditional parameters are not supported by the WebGPU prototype".to_string());
                };
                match &param.kind {
                    ParamKind::Resource | ParamKind::Broadcast => {
                        resources.push(resource_kind(param)?);
                    }
                    ParamKind::Scalar => {
                        hlsl_scalar_from_uint_word(&param.ty, "_")?;
                        scalar_count += 1;
                    }
                    ParamKind::SystemValue(_) | ParamKind::PassThrough => {}
                }
            }
        }
    }
    if !saw_graphics {
        return Ok(WgpuComputeLayout::inferred_storage());
    }
    Ok(WgpuComputeLayout {
        resources: Some(resources),
        scalar_count,
    })
}

/// Logical `DirectSpatial<T>` element types in author order for WebGPU storage specialization.
pub fn webgpu_direct_spatial_texels(source: &str, defines: &[(&str, &str)]) -> Result<Vec<String>, String> {
    let entries = find_all_entries(source);
    let mut texels = Vec::new();
    for entry in &entries {
        if entry.stage != Stage::Compute {
            continue;
        }
        texels.clear();
        for param in resolve_cuda_params(&entry.params, defines) {
            let ty = param.ty.trim();
            if ty.starts_with("DirectSpatial<") {
                let logical = cuda_texture_element(ty, "DirectSpatial<")?;
                texels.push(logical.split(',').next().unwrap_or(&logical).trim().to_string());
            }
        }
    }
    Ok(texels)
}

/// WebGPU compute lowering for `[goldy_compute]` entry points.
///
/// Unlike the native lowering, resources become fixed `@group(0)` bindings
/// (expressed as HLSL registers for Slang) and are passed directly to the
/// renamed user function. Single-word scalars (`uint`/`float`/`int`/`bool`) are
/// packed into a trailing `ConstantBuffer` of eight `uint` words, filled from
/// `BindResourcesRaw.user`.
pub fn transform_virtual_main_webgpu_compute(source: &str, defines: &[(&str, &str)]) -> Result<String, String> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(source.to_string());
    }

    fn resource_decl(param: &Param, binding: u32, name: &str) -> Result<String, String> {
        let ty = param.ty.trim();
        let (decl_ty, register) = if ty.starts_with("Scattered<") || ty == "ByteAddress" {
            (ty.to_string(), 'u')
        } else if ty.starts_with("BufRO<") || ty.starts_with("Interpolated<") {
            (ty.to_string(), 't')
        } else if ty.starts_with("DirectSpatial<") {
            let logical = cuda_texture_element(ty, "DirectSpatial<")?;
            let logical_elem = logical.split(',').next().unwrap_or(&logical).trim();
            (format!("RWTexture2D<{logical_elem}>"), 'u')
        } else if ty == "Filter" {
            (ty.to_string(), 's')
        } else if ty == "Accel" {
            ("RaytracingAccelerationStructure".to_string(), 't')
        } else if matches!(param.kind, ParamKind::Broadcast) {
            (format!("ConstantBuffer<{ty}>"), 'b')
        } else {
            return Err(format!("unsupported WebGPU resource parameter type `{ty}`"));
        };
        Ok(format!("{decl_ty} {name} : register({register}{binding}, space0);"))
    }

    let mut generated = String::from("// [generated by goldy virtual_main WebGPU lowering — do not edit]\n");
    let mut compute_entries = Vec::new();
    for entry in &entries {
        if entry.stage != Stage::Compute {
            continue;
        }
        compute_entries.push(entry);

        let mut binding = 0u32;
        let mut sv_index = 0u32;
        let mut user = 0u32;
        let mut signature = Vec::new();
        let mut body = String::new();
        let mut call_args = Vec::new();
        let mut resource_decls = String::new();

        for param in resolve_cuda_params(&entry.params, defines) {
            match &param.kind {
                ParamKind::Resource | ParamKind::Broadcast => {
                    let global = format!("_goldy_wgpu_binding_{binding}");
                    resource_decls.push_str(&resource_decl(&param, binding, &global)?);
                    resource_decls.push('\n');
                    if matches!(param.kind, ParamKind::Broadcast) {
                        body.push_str(&format!("    {} {} = {};\n", param.ty, param.name, global));
                        call_args.push(param.name.clone());
                    } else if param.ty.trim().starts_with("DirectSpatial<") {
                        let ty = param.ty.trim();
                        body.push_str(&format!("    {ty} {} = {ty}({});\n", param.name, global));
                        call_args.push(param.name.clone());
                    } else {
                        call_args.push(global);
                    }
                    binding += 1;
                }
                ParamKind::SystemValue(sv) => {
                    let arg = format!("_sv{sv_index}");
                    signature.push(format!("{} {} : {}", sv.primitive(), arg, sv.semantic()));
                    body.push_str(&format!("    {} {} = {}({});\n", param.ty, param.name, param.ty, arg));
                    call_args.push(param.name.clone());
                    sv_index += 1;
                }
                ParamKind::Scalar => {
                    let word = format!("_goldy_wgpu_user._uw{user}");
                    let init = hlsl_scalar_from_uint_word(&param.ty, &word)?;
                    body.push_str(&format!("    {} {} = {};\n", param.ty, param.name, init));
                    call_args.push(param.name.clone());
                    user += 1;
                    if user > 8 {
                        return Err("WebGPU prototype supports at most 8 scalar dispatch parameters".to_string());
                    }
                }
                ParamKind::PassThrough => {
                    return Err(format!(
                        "WebGPU compute entry has unsupported pass-through parameter `{}`",
                        param.name
                    ));
                }
            }
        }

        generated.push_str(&resource_decls);
        if user > 0 {
            generated.push_str(&format!(
                "struct _GoldyWgpuUserParams {{\n\
                 \tuint _uw0;\n\
                 \tuint _uw1;\n\
                 \tuint _uw2;\n\
                 \tuint _uw3;\n\
                 \tuint _uw4;\n\
                 \tuint _uw5;\n\
                 \tuint _uw6;\n\
                 \tuint _uw7;\n\
                 }};\n\
                 ConstantBuffer<_GoldyWgpuUserParams> _goldy_wgpu_user : register(b{binding}, space0);\n"
            ));
        }

        generated.push_str(entry.stage.shader_attr());
        generated.push('\n');
        if let Some((x, y, z)) = entry.numthreads {
            generated.push_str(&format!("[numthreads({x}, {y}, {z})]\n"));
        }
        generated.push_str(&format!(
            "{} {}({}) {{\n{}",
            entry.return_type,
            entry.fn_name,
            signature.join(", "),
            body
        ));
        let user_fn = format!("_goldy_user_{}", entry.fn_name);
        if entry.return_type == "void" {
            generated.push_str(&format!("    {user_fn}({});\n", call_args.join(", ")));
        } else {
            generated.push_str(&format!("    return {user_fn}({});\n", call_args.join(", ")));
        }
        generated.push_str("}\n\n");
    }

    if compute_entries.is_empty() {
        return Err("WebGPU compute lowering found no [goldy_compute] entry point".to_string());
    }

    let mut modified = source.to_string();
    for entry in compute_entries.iter().rev() {
        apply_entry_transforms(&mut modified, entry);
    }
    Ok(generated + "#line 1\n" + &modified)
}

/// WebGPU vertex/fragment lowering for `[goldy_vertex]` / `[goldy_fragment]`.
///
/// Same packed `@group(0)` model as compute: resources become HLSL registers in
/// vertex-then-fragment author order. Stage inputs stay as pass-through parameters.
///
/// `Scattered<T>` is lowered as read-only `BufRO<T>` so WGSL uses `storage, read`
/// (portable WebGPU; no `VERTEX_WRITABLE_STORAGE`).
pub fn transform_virtual_main_webgpu_graphics(source: &str) -> Result<String, String> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(source.to_string());
    }

    fn resource_decl(param: &Param, binding: u32, name: &str) -> Result<String, String> {
        let ty = param.ty.trim();
        let (decl_ty, register) =
            if let Some(elem) = ty.strip_prefix("Scattered<").and_then(|rest| rest.strip_suffix('>')) {
                (format!("BufRO<{elem}>"), 't')
            } else if ty == "ByteAddress" || ty.starts_with("BufRO<") || ty.starts_with("Interpolated<") {
                (ty.to_string(), 't')
            } else if ty.starts_with("DirectSpatial<") {
                let logical = cuda_texture_element(ty, "DirectSpatial<")?;
                let logical_elem = logical.split(',').next().unwrap_or(&logical).trim();
                (format!("RWTexture2D<{logical_elem}>"), 'u')
            } else if ty == "Filter" {
                (ty.to_string(), 's')
            } else if matches!(param.kind, ParamKind::Broadcast) {
                (format!("ConstantBuffer<{ty}>"), 'b')
            } else {
                return Err(format!("unsupported WebGPU resource parameter type `{ty}`"));
            };
        Ok(format!("{decl_ty} {name} : register({register}{binding}, space0);"))
    }

    let graphics_entries: Vec<&EntryDef> = entries
        .iter()
        .filter(|entry| matches!(entry.stage, Stage::Vertex | Stage::Fragment))
        .collect();
    if graphics_entries.is_empty() {
        return Err("WebGPU graphics lowering found no [goldy_vertex]/[goldy_fragment] entry point".to_string());
    }

    let mut generated = String::from("// [generated by goldy virtual_main WebGPU graphics lowering — do not edit]\n");
    let mut binding = 0u32;
    let mut user = 0u32;
    let mut wrappers = String::new();

    for entry in &graphics_entries {
        let mut signature = Vec::new();
        let mut body = String::new();
        let mut call_args = Vec::new();
        let mut sv_index = 0u32;

        for item in &entry.params {
            let ParamItem::Single(param) = item else {
                return Err("conditional parameters are not supported by the WebGPU prototype".to_string());
            };
            match &param.kind {
                ParamKind::Resource | ParamKind::Broadcast => {
                    let global = format!("_goldy_wgpu_binding_{binding}");
                    generated.push_str(&resource_decl(param, binding, &global)?);
                    generated.push('\n');
                    if matches!(param.kind, ParamKind::Broadcast) {
                        body.push_str(&format!("    {} {} = {};\n", param.ty, param.name, global));
                        call_args.push(param.name.clone());
                    } else if param.ty.trim().starts_with("DirectSpatial<") {
                        let ty = param.ty.trim();
                        body.push_str(&format!("    {ty} {} = {ty}({});\n", param.name, global));
                        call_args.push(param.name.clone());
                    } else {
                        call_args.push(global);
                    }
                    binding += 1;
                }
                ParamKind::SystemValue(sv) => {
                    let arg = format!("_sv{sv_index}");
                    signature.push(format!("{} {} : {}", sv.primitive(), arg, sv.semantic()));
                    body.push_str(&format!("    {} {} = {}({});\n", param.ty, param.name, param.ty, arg));
                    call_args.push(param.name.clone());
                    sv_index += 1;
                }
                ParamKind::Scalar => {
                    let word = format!("_goldy_wgpu_user._uw{user}");
                    let init = hlsl_scalar_from_uint_word(&param.ty, &word)?;
                    body.push_str(&format!("    {} {} = {};\n", param.ty, param.name, init));
                    call_args.push(param.name.clone());
                    user += 1;
                    if user > 8 {
                        return Err("WebGPU prototype supports at most 8 scalar dispatch parameters".to_string());
                    }
                }
                ParamKind::PassThrough => {
                    signature.push(format!("{} {}", param.ty, param.name));
                    call_args.push(param.name.clone());
                }
            }
        }

        let semantic_suffix = entry
            .return_semantic
            .as_ref()
            .map(|semantic| format!(" : {semantic}"))
            .unwrap_or_default();
        wrappers.push_str(entry.stage.shader_attr());
        wrappers.push('\n');
        wrappers.push_str(&format!(
            "{} {}({}){semantic_suffix} {{\n{}",
            entry.return_type,
            entry.fn_name,
            signature.join(", "),
            body
        ));
        let user_fn = format!("_goldy_user_{}", entry.fn_name);
        if entry.return_type == "void" {
            wrappers.push_str(&format!("    {user_fn}({});\n", call_args.join(", ")));
        } else {
            wrappers.push_str(&format!("    return {user_fn}({});\n", call_args.join(", ")));
        }
        wrappers.push_str("}\n\n");
    }

    if user > 0 {
        generated.push_str(&format!(
            "struct _GoldyWgpuUserParams {{\n\
             \tuint _uw0;\n\
             \tuint _uw1;\n\
             \tuint _uw2;\n\
             \tuint _uw3;\n\
             \tuint _uw4;\n\
             \tuint _uw5;\n\
             \tuint _uw6;\n\
             \tuint _uw7;\n\
             }};\n\
             ConstantBuffer<_GoldyWgpuUserParams> _goldy_wgpu_user : register(b{binding}, space0);\n"
        ));
    }
    generated.push_str(&wrappers);

    let mut modified = source.to_string();
    for entry in graphics_entries.iter().rev() {
        apply_entry_transforms(&mut modified, entry);
    }
    rewrite_graphics_scattered_as_bufro(&mut modified, &graphics_entries);
    Ok(generated + "#line 1\n" + &modified)
}

/// Kind of CUDA kernel launch argument corresponding to one author-facing
/// `[goldy_compute]` parameter (system values are omitted — they come from the
/// launch grid, not host-passed args).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CudaLaunchArgKind {
    /// Consumes the next `BindResourcesRaw.indices` registry key → `CudaBufferArg`.
    Buffer,
    /// Consumes the next registry key → `CUtexObject` (`Interpolated<T>` / `Texture2D`).
    SampledTexture {
        /// Inner element type string (e.g. `"float4"`).
        element: String,
    },
    /// Consumes the next registry key → `CUsurfObject` (`DirectSpatial<T>` / `RWTexture2D`).
    StorageTexture {
        /// Inner element type string (e.g. `"float4"`).
        element: String,
    },
    /// Consumes the next registry key → ignored `SamplerState` word (`Filter`).
    ///
    /// Slang still emits a pointer-sized kernel parameter; the host passes zero.
    /// Filtering is baked into each `CUtexObject` from the bound sampler desc.
    Sampler,
    /// Consumes the next `BindResourcesRaw.user` u32 word.
    Scalar,
}

impl CudaLaunchArgKind {
    /// True when this kind consumes one entry from `BindResourcesRaw.indices`.
    pub fn consumes_registry_index(&self) -> bool {
        !matches!(self, Self::Scalar)
    }
}

/// Per-`DirectSpatial` CUDA specialization for typed-UAV format conversion.
///
/// Indexed in author order among `DirectSpatial<*>` parameters only (not all
/// launch-layout slots). Identity keeps size-matched raw surfaces; `Float4Rgba8Unorm`
/// rewrites that entry parameter to `DirectSpatial<float4, uint8_t4>`.
///
/// Specs are applied **per binding**: a single dispatch may mix `Rgba32Float`
/// (identity `DirectSpatial<float4>`) and `Rgba8Unorm` (`DirectSpatial<float4, uint8_t4>`)
/// slots. Helpers that take `DirectSpatial<float4>` get a matching
/// `DirectSpatial<float4, uint8_t4>` overload injected by specialization.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum CudaStorageTextureSpec {
    /// Raw `DirectSpatial<T>` ↔ size-matched texture format (`S = T`).
    #[default]
    Identity,
    /// `DirectSpatial<float4>` bound to `Rgba8Unorm` → `DirectSpatial<float4, uint8_t4>`.
    Float4Rgba8Unorm,
    /// `DirectSpatial<float4>` bound to `Bgra8Unorm` (WebGPU `bgra8unorm` storage).
    Float4Bgra8Unorm,
}

impl CudaStorageTextureSpec {
    /// Derive specialization from logical shader element type and bound texture format.
    pub fn from_element_and_format(element: &str, format: crate::types::TextureFormat) -> Result<Self, String> {
        use crate::types::TextureFormat;
        let element = element.trim();
        match (element, format) {
            ("float4", TextureFormat::Rgba32Float)
            | ("half4", TextureFormat::Rgba16Float)
            | ("uint8_t4", TextureFormat::Rgba8Unorm)
            | ("vector<uint8_t, 4>", TextureFormat::Rgba8Unorm)
            | ("vector<uint8_t,4>", TextureFormat::Rgba8Unorm) => Ok(Self::Identity),
            ("float4", TextureFormat::Rgba8Unorm) => Ok(Self::Float4Rgba8Unorm),
            ("float4", TextureFormat::Bgra8Unorm) => Ok(Self::Float4Bgra8Unorm),
            _ => Err(format!(
                "DirectSpatial<{element}> cannot access {:?}; \
                 supported: float4↔Rgba32Float|Rgba8Unorm|Bgra8Unorm (packed), half4↔Rgba16Float, uint8_t4↔Rgba8Unorm",
                format
            )),
        }
    }

    /// True when this specialization packs logical float4 through an rgba8 surface.
    pub fn packs_float4_as_rgba8(self) -> bool {
        matches!(self, Self::Float4Rgba8Unorm)
    }

    /// WGSL storage texel format to rewrite from Slang's identity `rgba32float`, if any.
    pub fn wgsl_storage_texel_format(self) -> Option<&'static str> {
        match self {
            Self::Identity => None,
            Self::Float4Rgba8Unorm => Some("rgba8unorm"),
            Self::Float4Bgra8Unorm => Some("bgra8unorm"),
        }
    }
}

/// Build per-`DirectSpatial` specs for a launch layout given bound storage-texture formats
/// in launch-layout order among `StorageTexture` slots only.
pub fn derive_cuda_storage_texture_specs(
    layout: &[CudaLaunchArgKind],
    storage_formats: &[crate::types::TextureFormat],
) -> Result<Vec<CudaStorageTextureSpec>, String> {
    let mut specs = Vec::new();
    let mut format_i = 0usize;
    for kind in layout {
        let CudaLaunchArgKind::StorageTexture { element } = kind else {
            continue;
        };
        let format = storage_formats.get(format_i).copied().ok_or_else(|| {
            format!(
                "CUDA: missing texture format for DirectSpatial slot {format_i} (have {} formats)",
                storage_formats.len()
            )
        })?;
        format_i += 1;
        specs.push(CudaStorageTextureSpec::from_element_and_format(element, format)?);
    }
    if format_i != storage_formats.len() {
        return Err(format!(
            "CUDA: expected {} storage texture formats, got {}",
            format_i,
            storage_formats.len()
        ));
    }
    Ok(specs)
}

fn cuda_texture_element(ty: &str, prefix: &str) -> Result<String, String> {
    let ty = ty.trim();
    if ty.starts_with(prefix) && ty.ends_with('>') {
        let inner = ty[prefix.len()..ty.len() - 1].trim();
        if inner.is_empty() {
            return Err(format!("CUDA texture type `{ty}` has an empty element type"));
        }
        Ok(inner.to_string())
    } else {
        Err(format!("expected `{prefix}T>`, got `{ty}`"))
    }
}

/// Resolve `#ifdef` parameter blocks using the same preprocessor defines Slang
/// will see for this compilation (e.g. `msaa` for fine MSAA variants).
fn resolve_cuda_params(params: &[ParamItem], defines: &[(&str, &str)]) -> Vec<Param> {
    let defined: std::collections::HashSet<&str> = defines.iter().map(|(k, _)| *k).collect();
    let mut out = Vec::new();
    for item in params {
        match item {
            ParamItem::Single(param) => out.push(param.clone()),
            ParamItem::Conditional {
                condition,
                then_params,
                else_params,
            } => {
                if defined.contains(condition.as_str()) {
                    out.extend(then_params.iter().cloned());
                } else {
                    out.extend(else_params.iter().cloned());
                }
            }
        }
    }
    out
}

/// Extract the CUDA launch-arg layout for the primary `[goldy_compute]` entry.
///
/// Order matches author parameter order with system values skipped. Empty when
/// the source has no `[goldy_compute]` entries (plain Slang compute passthrough).
///
/// `#ifdef` parameter blocks are resolved against `defines` (must match the
/// defines passed to Slang for this shader variant).
pub fn extract_cuda_compute_launch_layout(
    source: &str,
    defines: &[(&str, &str)],
) -> Result<Vec<CudaLaunchArgKind>, String> {
    let entries = find_all_entries(source);
    let Some(entry) = entries.iter().find(|e| e.stage == Stage::Compute) else {
        return Ok(Vec::new());
    };
    if entries.iter().any(|e| e.stage != Stage::Compute) {
        return Err("CUDA prototype only lowers [goldy_compute] entry points".to_string());
    }

    let mut layout = Vec::new();
    for param in resolve_cuda_params(&entry.params, defines) {
        match &param.kind {
            ParamKind::Broadcast => layout.push(CudaLaunchArgKind::Buffer),
            ParamKind::Resource => {
                let ty = param.ty.trim();
                if ty.starts_with("Interpolated<") {
                    layout.push(CudaLaunchArgKind::SampledTexture {
                        element: cuda_texture_element(ty, "Interpolated<")?,
                    });
                } else if ty.starts_with("DirectSpatial<") {
                    layout.push(CudaLaunchArgKind::StorageTexture {
                        element: cuda_texture_element(ty, "DirectSpatial<")?,
                    });
                } else if ty == "Filter" {
                    layout.push(CudaLaunchArgKind::Sampler);
                } else if ty.starts_with("Scattered<") || ty == "ByteAddress" || ty.starts_with("BufRO<") {
                    layout.push(CudaLaunchArgKind::Buffer);
                } else {
                    return Err(format!("unsupported CUDA resource parameter type `{ty}`"));
                }
            }
            ParamKind::Scalar => {
                hlsl_scalar_from_uint_word(&param.ty, "_")?;
                layout.push(CudaLaunchArgKind::Scalar);
            }
            ParamKind::SystemValue(_) => {}
            ParamKind::PassThrough => {
                return Err(format!(
                    "CUDA compute entry has unsupported pass-through parameter `{}`",
                    param.name
                ));
            }
        }
    }
    Ok(layout)
}

/// Reinterpret a `uniform uint` word into the author scalar type (HLSL).
fn hlsl_scalar_from_uint_word(ty: &str, word: &str) -> Result<String, String> {
    match ty.trim() {
        "uint" => Ok(word.to_string()),
        "float" => Ok(format!("asfloat({word})")),
        "int" => Ok(format!("asint({word})")),
        "bool" => Ok(format!("{word} != 0u")),
        other => Err(format!(
            "compute prototype only lowers single-word scalar types (uint/float/int/bool); \
             got `{other}` — bind a broadcast buffer for wider uniforms"
        )),
    }
}

/// CUDA compute lowering for `[goldy_compute]` entry points.
///
/// Unlike the native push-constant / bindless-heap lowering, each buffer resource
/// becomes a `uniform StructuredBuffer` / `RWStructuredBuffer` entry-point
/// parameter. Slang's CUDA target lowers those to `{T* data; size_t count}`
/// descriptors that the backend fills from `CUdeviceptr` at launch time.
///
/// Textures become `uniform Texture2D` / `RWTexture2D` (→ `CUtexObject` /
/// `CUsurfObject`); samplers become `uniform SamplerState` (pointer-sized,
/// ignored by Slang — filtering is baked into each texture object).
///
/// Broadcast structs are passed as a one-element read-only structured buffer and
/// loaded at index 0. Single-word scalars (`uint`/`float`/`int`/`bool`) become
/// `uniform uint` kernel args (Goldy `with_param` words). Multi-word scalars and
/// graphics stages are rejected.
///
/// `#ifdef` parameter blocks are resolved against `defines` so MSAA fine variants
/// get a concrete CUDA launch signature matching the Slang preprocessor view.
pub fn transform_virtual_main_cuda_compute(source: &str, defines: &[(&str, &str)]) -> Result<String, String> {
    transform_virtual_main_cuda_compute_specialized(source, defines, &[])
}

/// CUDA `[goldy_compute]` lowering with optional per-`DirectSpatial` format specialization.
///
/// `storage_specs` is indexed in author order among `DirectSpatial<*>` parameters for each
/// entry. An empty slice means identity (size-matched raw surfaces) for every slot.
pub fn transform_virtual_main_cuda_compute_specialized(
    source: &str,
    defines: &[(&str, &str)],
    storage_specs: &[CudaStorageTextureSpec],
) -> Result<String, String> {
    let entries = find_all_entries(source);
    if entries.is_empty() {
        return Ok(source.to_string());
    }

    fn resource_param_ty(param: &Param) -> Result<String, String> {
        let ty = param.ty.trim();
        if ty.starts_with("Scattered<")
            || ty == "ByteAddress"
            || ty.starts_with("BufRO<")
            || ty.starts_with("Interpolated<")
            || ty.starts_with("DirectSpatial<")
            || ty == "Filter"
            || ty == "Accel"
        {
            Ok(ty.to_string())
        } else if matches!(param.kind, ParamKind::Broadcast) {
            // One-element read-only buffer; wrapper loads `[0]`.
            Ok(format!("StructuredBuffer<{ty}>"))
        } else {
            Err(format!("unsupported CUDA resource parameter type `{ty}`"))
        }
    }

    // `(user_fn_name, param_name, new_type)` — rewrite user helper signatures after rename.
    let mut user_param_rewrites: Vec<(String, String, String)> = Vec::new();

    let mut generated = String::from("// [generated by goldy virtual_main CUDA lowering — do not edit]\n");
    for entry in &entries {
        if entry.stage != Stage::Compute {
            return Err("CUDA prototype only lowers [goldy_compute] entry points".to_string());
        }

        let mut signature = Vec::new();
        let mut body = String::new();
        let mut call_args = Vec::new();
        let mut sv_index = 0u32;
        let mut binding = 0u32;
        let mut user = 0u32;
        let mut storage_spec_i = 0usize;
        let user_fn = format!("_goldy_user_{}", entry.fn_name);

        for param in resolve_cuda_params(&entry.params, defines) {
            match &param.kind {
                ParamKind::Resource | ParamKind::Broadcast => {
                    let global = format!("_goldy_cuda_binding_{binding}");
                    let ty = param.ty.trim();
                    if ty == "ByteAddress" {
                        // CUDA/NVRTC has no RWByteAddressBuffer.Store; bind as
                        // Scattered<uint> and wrap into ByteAddressView.
                        signature.push(format!("uniform Scattered<uint> {global}"));
                        body.push_str(&format!("    ByteAddress {} = ByteAddress({});\n", param.name, global));
                        call_args.push(param.name.clone());
                    } else if ty.starts_with("DirectSpatial<") {
                        let spec = if storage_specs.is_empty() {
                            CudaStorageTextureSpec::Identity
                        } else {
                            *storage_specs.get(storage_spec_i).ok_or_else(|| {
                                format!(
                                    "CUDA specialization: missing storage-texture spec for DirectSpatial slot {storage_spec_i}"
                                )
                            })?
                        };
                        storage_spec_i += 1;
                        let logical = cuda_texture_element(ty, "DirectSpatial<")?;
                        // Author `DirectSpatial<T>` may include commas only in nested
                        // forms; identity uses the first type argument as storage.
                        let logical_elem = logical.split(',').next().unwrap_or(&logical).trim();
                        match spec {
                            CudaStorageTextureSpec::Identity => {
                                // Bind the raw UAV and wrap into DirectSpatial<T>.
                                signature.push(format!("uniform RWTexture2D<{logical_elem}> {global}"));
                                body.push_str(&format!(
                                    "    DirectSpatial<{logical_elem}> {} = DirectSpatial<{logical_elem}>({});\n",
                                    param.name, global
                                ));
                                call_args.push(param.name.clone());
                            }
                            CudaStorageTextureSpec::Float4Rgba8Unorm => {
                                if logical_elem != "float4" {
                                    return Err(format!(
                                        "CUDA specialization Float4Rgba8Unorm requires DirectSpatial<float4>, got `{ty}`"
                                    ));
                                }
                                let wrapped_ty = "DirectSpatial<float4, uint8_t4>";
                                signature.push(format!("uniform RWTexture2D<uint8_t4> {global}"));
                                body.push_str(&format!(
                                    "    {wrapped_ty} {} = {wrapped_ty}({});\n",
                                    param.name, global
                                ));
                                call_args.push(param.name.clone());
                                user_param_rewrites.push((user_fn.clone(), param.name.clone(), wrapped_ty.to_string()));
                            }
                            CudaStorageTextureSpec::Float4Bgra8Unorm => {
                                return Err(
                                    "CUDA does not specialize DirectSpatial<float4> to Bgra8Unorm storage".into()
                                );
                            }
                        }
                    } else {
                        let param_ty = resource_param_ty(&param)?;
                        signature.push(format!("uniform {param_ty} {global}"));
                        if matches!(param.kind, ParamKind::Broadcast) {
                            body.push_str(&format!("    {} {} = {}[0];\n", param.ty, param.name, global));
                            call_args.push(param.name.clone());
                        } else {
                            call_args.push(global);
                        }
                    }
                    binding += 1;
                }
                ParamKind::SystemValue(sv) => {
                    let arg = format!("_sv{sv_index}");
                    signature.push(format!("{} {} : {}", sv.primitive(), arg, sv.semantic()));
                    body.push_str(&format!("    {} {} = {}({});\n", param.ty, param.name, param.ty, arg));
                    call_args.push(param.name.clone());
                    sv_index += 1;
                }
                ParamKind::Scalar => {
                    let word = format!("_goldy_cuda_user_{user}");
                    let init = hlsl_scalar_from_uint_word(&param.ty, &word)?;
                    signature.push(format!("uniform uint {word}"));
                    body.push_str(&format!("    {} {} = {};\n", param.ty, param.name, init));
                    call_args.push(param.name.clone());
                    user += 1;
                }
                ParamKind::PassThrough => {
                    return Err(format!(
                        "CUDA compute entry has unsupported pass-through parameter `{}`",
                        param.name
                    ));
                }
            }
        }

        if !storage_specs.is_empty() && storage_spec_i != storage_specs.len() {
            return Err(format!(
                "CUDA specialization: expected {} DirectSpatial slots, found {storage_spec_i}",
                storage_specs.len()
            ));
        }

        generated.push_str(entry.stage.shader_attr());
        generated.push('\n');
        if let Some((x, y, z)) = entry.numthreads {
            generated.push_str(&format!("[numthreads({x}, {y}, {z})]\n"));
        }
        generated.push_str(&format!(
            "{} {}({}) {{\n{}",
            entry.return_type,
            entry.fn_name,
            signature.join(", "),
            body
        ));
        if entry.return_type == "void" {
            generated.push_str(&format!("    {user_fn}({});\n", call_args.join(", ")));
        } else {
            generated.push_str(&format!("    return {user_fn}({});\n", call_args.join(", ")));
        }
        generated.push_str("}\n\n");
    }

    let mut modified = source.to_string();
    for entry in entries.iter().rev() {
        apply_entry_transforms(&mut modified, entry);
    }
    // Per-binding: only rewrite packed rgba8 entry params to DirectSpatial<float4, uint8_t4>.
    // Identity DirectSpatial<float4> slots stay as-is so mixed float+unorm dispatches work.
    let needs_packed_helper_overloads = !user_param_rewrites.is_empty();
    for (user_fn, param_name, new_ty) in &user_param_rewrites {
        rewrite_cuda_user_direct_spatial_param(&mut modified, user_fn, param_name, new_ty)?;
    }
    if needs_packed_helper_overloads {
        inject_direct_spatial_float4_packed_overloads(&mut modified, "DirectSpatial<float4, uint8_t4>")?;
    }
    Ok(generated + "#line 1\n" + &modified)
}

/// Rewrite `DirectSpatial<float4> {param}` → `{new_ty} {param}` in a renamed user helper signature.
///
/// Replaces **all** occurrences inside the parameter list so `#ifdef` / `#else` branches that
/// repeat the same parameter name (e.g. ekrano `fine.slang` filter layers) both get updated.
fn rewrite_cuda_user_direct_spatial_param(
    source: &mut String,
    user_fn: &str,
    param_name: &str,
    new_ty: &str,
) -> Result<(), String> {
    let needle = format!("{user_fn}(");
    let start = source.find(&needle).ok_or_else(|| {
        format!("CUDA specialization: renamed user function `{user_fn}` not found for param `{param_name}`")
    })?;
    let sig_start = start + needle.len();
    let bytes = source.as_bytes();
    let mut depth = 1i32;
    let mut i = sig_start;
    while i < bytes.len() && depth > 0 {
        match bytes[i] {
            b'(' => depth += 1,
            b')' => depth -= 1,
            _ => {}
        }
        i += 1;
    }
    if depth != 0 {
        return Err(format!("CUDA specialization: could not parse signature of `{user_fn}`"));
    }
    let sig_end = i - 1;
    let old_pat = format!("DirectSpatial<float4> {param_name}");
    let new_pat = format!("{new_ty} {param_name}");
    let sig = &source[sig_start..sig_end];
    if !sig.contains(&old_pat) {
        return Err(format!(
            "CUDA specialization: expected `{old_pat}` in `{user_fn}` signature for rgba8 view rewrite"
        ));
    }
    let rewritten = sig.replace(&old_pat, &new_pat);
    source.replace_range(sig_start..sig_end, &rewritten);
    Ok(())
}

/// Clone free helpers that take `DirectSpatial<float4>` so packed
/// `DirectSpatial<float4, uint8_t4>` call sites type-check without author changes.
///
/// Skips Goldy-generated `_goldy_*` symbols. Each matching function body is duplicated
/// with `DirectSpatial<float4>` → `DirectSpatial<float4, uint8_t4>` in the signature and body
/// parameter types (body uses the same identifiers; only the signature types change).
fn inject_direct_spatial_float4_packed_overloads(source: &mut String, packed: &str) -> Result<(), String> {
    const IDENTITY: &str = "DirectSpatial<float4>";
    let packed_ty = packed;

    // Collect unique function spans that need an overload.
    let mut fn_spans: Vec<(usize, usize)> = Vec::new();
    let mut search_from = 0usize;
    while let Some(rel) = source[search_from..].find(IDENTITY) {
        let at = search_from + rel;
        // Skip already-packed forms (`DirectSpatial<float4, …>`).
        let after = at + IDENTITY.len();
        if source.as_bytes().get(after) == Some(&b',') {
            search_from = after;
            continue;
        }
        let Some((fn_start, fn_end)) = find_enclosing_function_span(source, at) else {
            search_from = after;
            continue;
        };
        let header = &source[fn_start..at];
        // Skip Goldy-generated entry wrappers / renamed user mains.
        if header.contains("_goldy_") {
            search_from = after;
            continue;
        }
        // Only parameter-list occurrences (roughly: still inside `(`…`)` before `{`).
        if !fn_param_list_contains_offset(source, fn_start, at) {
            search_from = after;
            continue;
        }
        if !fn_spans.iter().any(|&(s, e)| s == fn_start && e == fn_end) {
            fn_spans.push((fn_start, fn_end));
        }
        search_from = after;
    }

    if fn_spans.is_empty() {
        return Ok(());
    }

    // Insert overloads after each original, back-to-front so earlier offsets stay valid.
    fn_spans.sort_by_key(|(s, _)| *s);
    for &(fn_start, fn_end) in fn_spans.iter().rev() {
        let original = source[fn_start..fn_end].to_string();
        if original.contains(packed_ty) {
            continue;
        }
        let overload = original.replace(IDENTITY, packed_ty);
        if overload == original {
            continue;
        }
        let insertion = format!("\n\n// [goldy] {packed_ty} overload\n{overload}");
        source.insert_str(fn_end, &insertion);
    }
    Ok(())
}

/// Best-effort: walk left from `pos` to a line that looks like a function declarator,
/// then scan braces to the matching close.
fn find_enclosing_function_span(source: &str, pos: usize) -> Option<(usize, usize)> {
    let bytes = source.as_bytes();
    // Walk left to the start of the statement / previous closing brace.
    let mut i = pos;
    while i > 0 {
        // Prefer starting at a newline followed by a type-ish token (not indented comment only).
        if bytes[i - 1] == b'\n' {
            let line_start = i;
            let line_end = source[line_start..]
                .find('\n')
                .map(|n| line_start + n)
                .unwrap_or(source.len());
            let line = source[line_start..line_end].trim_start();
            if line.starts_with("//") || line.starts_with('#') || line.is_empty() {
                i -= 1;
                continue;
            }
            // Function defs typically contain `(` before `{` on this or following lines.
            if let Some(brace_rel) = source[line_start..].find('{') {
                let brace = line_start + brace_rel;
                if brace > pos {
                    // `{` is after our DirectSpatial — good candidate if `(` is between line_start and brace
                    // and DirectSpatial is between `(` and `)`.
                    if let Some(paren_rel) = source[line_start..brace].find('(') {
                        let paren = line_start + paren_rel;
                        if paren < pos && pos < brace {
                            let end = match_brace(source, brace)?;
                            return Some((line_start, end));
                        }
                    }
                }
            }
        }
        i -= 1;
        // Bound search: don't walk endlessly through a huge file for one hit.
        if pos - i > 4000 {
            break;
        }
    }
    None
}

fn match_brace(source: &str, open_brace: usize) -> Option<usize> {
    let bytes = source.as_bytes();
    if bytes.get(open_brace) != Some(&b'{') {
        return None;
    }
    let mut depth = 0i32;
    let mut i = open_brace;
    while i < bytes.len() {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i + 1);
                }
            }
            _ => {}
        }
        i += 1;
    }
    None
}

fn fn_param_list_contains_offset(source: &str, fn_start: usize, offset: usize) -> bool {
    let bytes = source.as_bytes();
    let Some(paren_rel) = source[fn_start..].find('(') else {
        return false;
    };
    let paren = fn_start + paren_rel;
    if offset < paren {
        return false;
    }
    let mut depth = 0i32;
    let mut i = paren;
    while i < bytes.len() && i <= offset {
        match bytes[i] {
            b'(' => depth += 1,
            b')' => {
                depth -= 1;
                if depth == 0 {
                    return i >= offset;
                }
            }
            b'{' if depth == 1 => return false,
            _ => {}
        }
        i += 1;
    }
    depth > 0
}

/// Slang translation-unit source after the optional virtual-main rewrite.
///
/// This matches the compiler gate: [`transform_virtual_main`] runs only when `source`
/// contains `[goldy_compute]`, `[goldy_vertex]`, or `[goldy_fragment]` as substrings
/// (the same [`str::contains`] checks previously used before calling Slang).
///
/// Callers that feed Slang directly (disk cache keys, `add_translation_unit_source_string`) should
/// use this so the hashed text matches the compiled text.
pub fn effective_slang_source_for_compile(source: &str) -> Cow<'_, str> {
    let has_compute = source.contains("[goldy_compute]");
    #[cfg(feature = "graphics")]
    let has_graphics_stage = source.contains("[goldy_vertex]") || source.contains("[goldy_fragment]");
    #[cfg(not(feature = "graphics"))]
    let has_graphics_stage = false;
    if has_compute || has_graphics_stage {
        Cow::Owned(transform_virtual_main(source))
    } else {
        Cow::Borrowed(source)
    }
}

