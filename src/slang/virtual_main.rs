/// Mutable index counters shared while emitting a wrapper (`emit_wrapper`).
struct WrapperIndices<'a> {
    bindless_idx: &'a mut u32,
    user_idx: &'a mut u32,
    sv_idx: &'a mut u32,
    pt_idx: &'a mut u32,
}

/// Accumulates the three parallel output streams needed to build a generated
/// `[shader(...)]` wrapper: the function signature parameter list, the body
/// (init statements), and the argument list for the call to the user function.
///
/// Handles both plain parameters and `#ifdef`/`#else`/`#endif` conditional
/// blocks that may appear inside the parameter list.
struct WrapperBuilder {
    sig: String,
    body: String,
    call: String,
    sig_sep: bool,
    call_sep: bool,
}

impl WrapperBuilder {
    fn new() -> Self {
        Self {
            sig: String::new(),
            body: String::new(),
            call: String::new(),
            sig_sep: false,
            call_sep: false,
        }
    }

    fn push_sig(&mut self, s: &str) {
        if self.sig_sep {
            self.sig.push_str(", ");
        }
        self.sig.push_str(s);
        self.sig_sep = true;
    }

    fn push_call(&mut self, s: &str) {
        if self.call_sep {
            self.call.push_str(", ");
        }
        self.call.push_str(s);
        self.call_sep = true;
    }

    fn push_body_stmt(&mut self, s: &str) {
        if !s.is_empty() {
            self.body.push_str(s);
            self.body.push('\n');
        }
    }

    fn process_param(
        &mut self,
        param: &Param,
        bindless_idx: &mut u32,
        user_idx: &mut u32,
        sv_idx: &mut u32,
        pt_idx: &mut u32,
    ) {
        match &param.kind {
            ParamKind::Resource => {
                let k = *bindless_idx;
                *bindless_idx += 1;
                // Extract u16 from the appropriate bindless word: _bw{k/2}, low or high half.
                let word = k / 2;
                let extract = if k.is_multiple_of(2) {
                    format!("_bw{} & 0xFFFFu", word)
                } else {
                    format!("(_bw{} >> 16u) & 0xFFFFu", word)
                };
                let init_expr = resource_init_expr(&param.ty, &extract);
                self.push_body_stmt(&format!("    {} {} = {};", param.ty, param.name, init_expr));
                self.push_call(&param.name);
            }
            ParamKind::SystemValue(sv) => {
                let gn = format!("_sv{}", *sv_idx);
                *sv_idx += 1;
                self.push_sig(&format!("{} {} : {}", sv.primitive(), gn, sv.semantic()));
                self.push_body_stmt(&format!(
                    "    {} {} = {}({});",
                    param.ty, param.name, param.ty, gn
                ));
                self.push_call(&param.name);
            }
            ParamKind::Broadcast => {
                let k = *bindless_idx;
                *bindless_idx += 1;
                let word = k / 2;
                let extract = if k.is_multiple_of(2) {
                    format!("_bw{} & 0xFFFFu", word)
                } else {
                    format!("(_bw{} >> 16u) & 0xFFFFu", word)
                };
                self.push_body_stmt(&format!(
                    "    {} {} = goldy_broadcast<{}>({});",
                    param.ty, param.name, param.ty, extract
                ));
                self.push_call(&param.name);
            }
            ParamKind::Scalar => {
                let j = *user_idx;
                *user_idx += 1;
                // User params are full u32 words at _uw{j}.
                // Use the appropriate HLSL bit-reinterpret intrinsic for the type.
                let init_expr = match param.ty.as_str() {
                    "float" => format!("asfloat(_uw{})", j),
                    "int" => format!("asint(_uw{})", j),
                    "uint" => format!("_uw{}", j),
                    "bool" => format!("_uw{} != 0u", j),
                    _ => format!("({})_uw{}", param.ty, j),
                };
                self.push_body_stmt(&format!("    {} {} = {};", param.ty, param.name, init_expr));
                self.push_call(&param.name);
            }
            ParamKind::PassThrough => {
                let gn = format!("_pt{}", *pt_idx);
                *pt_idx += 1;
                self.push_sig(&format!("{} {}", param.ty, gn));
                self.push_call(&gn);
            }
        }
    }

    /// Emit a `#ifdef cond … #else … #endif` conditional block.
    ///
    /// Both branches start with the same push/sv/pt indices (they are alternatives).
    /// After the block the shared indices advance to the maximum reached by either branch.
    ///
    /// The generated sig and call blocks include a trailing comma inside each branch
    /// so that the preprocessed result is always a valid comma-separated list, regardless
    /// of which branch the compiler chooses.  The caller's `sig_sep`/`call_sep` flags
    /// are reset to `false` after the block (the trailing comma takes their place).
    fn process_conditional(
        &mut self,
        cond: &str,
        then_params: &[Param],
        else_params: &[Param],
        idx: &mut WrapperIndices<'_>,
    ) {
        let start_bindless = *idx.bindless_idx;
        let start_user = *idx.user_idx;
        let start_sv = *idx.sv_idx;
        let start_pt = *idx.pt_idx;

        // Process then-branch with a fresh builder starting at the same indices.
        let mut t_bindless = start_bindless;
        let mut t_user = start_user;
        let mut t_sv = start_sv;
        let mut t_pt = start_pt;
        let mut then_b = WrapperBuilder::new();
        for p in then_params {
            then_b.process_param(p, &mut t_bindless, &mut t_user, &mut t_sv, &mut t_pt);
        }

        // Process else-branch starting at the same indices.
        let mut e_bindless = start_bindless;
        let mut e_user = start_user;
        let mut e_sv = start_sv;
        let mut e_pt = start_pt;
        let mut else_b = WrapperBuilder::new();
        for p in else_params {
            else_b.process_param(p, &mut e_bindless, &mut e_user, &mut e_sv, &mut e_pt);
        }

        // Advance shared indices to the maximum reached by either branch.
        *idx.bindless_idx = t_bindless.max(e_bindless);
        *idx.user_idx = t_user.max(e_user);
        *idx.sv_idx = t_sv.max(e_sv);
        *idx.pt_idx = t_pt.max(e_pt);

        // --- Conditional signature block ---
        // Add a leading comma before `#ifdef` if a previous param was emitted.
        if self.sig_sep {
            self.sig.push(',');
        }
        let then_sig_trail = if then_b.sig.is_empty() { "" } else { "," };
        let else_sig_trail = if else_b.sig.is_empty() { "" } else { "," };
        if else_b.sig.is_empty() {
            self.sig.push_str(&format!(
                "\n#ifdef {}\n    {}{}\n#endif\n",
                cond, then_b.sig, then_sig_trail
            ));
        } else {
            self.sig.push_str(&format!(
                "\n#ifdef {}\n    {}{}\n#else\n    {}{}\n#endif\n",
                cond, then_b.sig, then_sig_trail, else_b.sig, else_sig_trail
            ));
        }
        // The trailing comma inside the block replaces the separator for the next param.
        self.sig_sep = false;

        // --- Conditional body block ---
        if !then_b.body.is_empty() || !else_b.body.is_empty() {
            self.body.push_str(&format!("#ifdef {}\n", cond));
            self.body.push_str(&then_b.body);
            if !else_b.body.is_empty() {
                self.body.push_str("#else\n");
                self.body.push_str(&else_b.body);
            }
            self.body.push_str("#endif\n");
        }

        // --- Conditional call-args block ---
        if self.call_sep {
            self.call.push(',');
        }
        let then_call_trail = if then_b.call.is_empty() { "" } else { "," };
        let else_call_trail = if else_b.call.is_empty() { "" } else { "," };
        if else_b.call.is_empty() {
            self.call.push_str(&format!(
                "\n#ifdef {}\n    {}{}\n#endif\n",
                cond, then_b.call, then_call_trail
            ));
        } else {
            self.call.push_str(&format!(
                "\n#ifdef {}\n    {}{}\n#else\n    {}{}\n#endif\n",
                cond, then_b.call, then_call_trail, else_b.call, else_call_trail
            ));
        }
        self.call_sep = false;
    }
}

/// Emit the generated `[shader("...")]` wrapper for one entry point.
fn emit_wrapper(entry: &EntryDef) -> String {
    let mut out = String::new();

    // Stage attribute.
    out.push_str(entry.stage.shader_attr());
    out.push('\n');

    // Transfer [numthreads] for compute.
    if let Some((x, y, z)) = entry.numthreads {
        out.push_str(&format!("[numthreads({}, {}, {})]\n", x, y, z));
    }

    let user_fn_name = format!("_goldy_user_{}", entry.fn_name);

    let mut bindless_idx = 0u32;
    let mut user_idx = 0u32;
    let mut sv_idx = 0u32;
    let mut pt_idx = 0u32;
    let mut wb = WrapperBuilder::new();

    // Always emit all 8 bindless words (_bw0.._bw7) and 8 user words (_uw0.._uw7)
    // so that push constant offsets are fixed regardless of how many params are used.
    for i in 0..8u32 {
        wb.push_sig(&format!("uniform uint _bw{}", i));
    }
    for i in 0..8u32 {
        wb.push_sig(&format!("uniform uint _uw{}", i));
    }

    for item in &entry.params {
        match item {
            ParamItem::Single(param) => {
                wb.process_param(
                    param,
                    &mut bindless_idx,
                    &mut user_idx,
                    &mut sv_idx,
                    &mut pt_idx,
                );
            }
            ParamItem::Conditional {
                condition,
                then_params,
                else_params,
            } => {
                let mut idx = WrapperIndices {
                    bindless_idx: &mut bindless_idx,
                    user_idx: &mut user_idx,
                    sv_idx: &mut sv_idx,
                    pt_idx: &mut pt_idx,
                };
                wb.process_conditional(condition, then_params, else_params, &mut idx);
            }
        }
    }

    // --- Function signature ---
    let ret_sem = if let Some(ref sem) = entry.return_semantic {
        format!(" : {}", sem)
    } else {
        String::new()
    };

    out.push_str(&format!(
        "{} {}({}){}",
        entry.return_type, entry.fn_name, wb.sig, ret_sem
    ));
    out.push_str(" {\n");

    // --- Body init statements ---
    out.push_str(&wb.body);

    // --- Call to user function ---
    let is_void = entry.return_type == "void";
    if is_void {
        out.push_str(&format!("    {}({});\n", user_fn_name, wb.call));
    } else {
        out.push_str(&format!("    return {}({});\n", user_fn_name, wb.call));
    }

    out.push('}');
    out
}

