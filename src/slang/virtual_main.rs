/// Find `needle` in `source` starting at `from`. Returns the byte offset of
/// the first character of the match.
fn find_substr(source: &str, from: usize, needle: &str) -> Option<usize> {
    source[from..].find(needle).map(|i| from + i)
}

/// Return true if position `pos` in `source` is inside a `//` line comment.
fn is_in_line_comment(source: &str, pos: usize) -> bool {
    // Find the start of the line.
    let line_start = source[..pos].rfind('\n').map(|i| i + 1).unwrap_or(0);
    let line = &source[line_start..pos];
    // Check if `//` appears before pos on the same line, outside strings.
    line.contains("//")
}

/// Skip whitespace and `//` line comments in `source` starting at `pos`.
fn skip_whitespace_and_comments(source: &str, mut pos: usize) -> usize {
    let bytes = source.as_bytes();
    loop {
        // Skip whitespace.
        while pos < bytes.len()
            && (bytes[pos] == b' '
                || bytes[pos] == b'\t'
                || bytes[pos] == b'\n'
                || bytes[pos] == b'\r')
        {
            pos += 1;
        }
        // Skip // line comments.
        if pos + 1 < bytes.len() && bytes[pos] == b'/' && bytes[pos + 1] == b'/' {
            while pos < bytes.len() && bytes[pos] != b'\n' {
                pos += 1;
            }
            continue;
        }
        // Skip /* block comments */.
        if pos + 1 < bytes.len() && bytes[pos] == b'/' && bytes[pos + 1] == b'*' {
            pos += 2;
            while pos + 1 < bytes.len() {
                if bytes[pos] == b'*' && bytes[pos + 1] == b'/' {
                    pos += 2;
                    break;
                }
                pos += 1;
            }
            continue;
        }
        break;
    }
    pos
}

/// Scan an identifier (letters, digits, underscores) at `pos` in `source`.
/// Returns `(identifier, new_pos)`.
fn scan_identifier(source: &str, pos: usize) -> Option<(String, usize)> {
    let bytes = source.as_bytes();
    let start = pos;
    let mut end = pos;
    while end < bytes.len() && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_') {
        end += 1;
    }
    if end == start {
        None
    } else {
        Some((source[start..end].to_string(), end))
    }
}

/// Scan the contents of a `[...]` block.  `pos` must point at `[`.
/// Returns `(inner_content, pos_after_closing_bracket)`.
fn scan_bracket_block(source: &str, pos: usize) -> Option<(String, usize)> {
    let close = find_matching_close(source, pos, '[', ']')?;
    let inner = source[pos + 1..close].to_string();
    Some((inner, close + 1))
}

/// Find the matching closing bracket for the open bracket at `open_pos`.
/// Handles nesting of the same pair; ignores other bracket types.
fn find_matching_close(source: &str, open_pos: usize, open: char, close: char) -> Option<usize> {
    let bytes = source.as_bytes();
    if bytes.get(open_pos) != Some(&(open as u8)) {
        return None;
    }
    let mut depth = 0i32;
    for (byte_idx, ch) in source[open_pos..].char_indices() {
        let abs = open_pos + byte_idx;
        if ch == open {
            depth += 1;
        } else if ch == close {
            depth -= 1;
            if depth == 0 {
                return Some(abs);
            }
        }
    }
    None
}

/// Find the start of the attribute group that contains the `[goldy_*]` at
/// `attr_start`. An attribute group is a sequence of `[...]` blocks separated
/// only by whitespace/comments with no other code in between.
fn find_attr_group_start(source: &str, attr_start: usize) -> usize {
    // Walk backward from attr_start.
    let mut pos = attr_start;
    loop {
        // Skip whitespace backward.
        let prev = skip_backward_whitespace(source, pos);
        if prev == pos {
            break;
        }
        // If the character before is `]`, it's another attribute.
        if source.as_bytes().get(prev.saturating_sub(1)) == Some(&b']') {
            // Find the matching `[`.
            let close = prev - 1;
            if let Some(open) = find_matching_open(source, close, '[', ']') {
                pos = open;
                continue;
            }
        }
        break;
    }
    pos
}

/// Walk backward from `pos` past whitespace. Returns new position.
fn skip_backward_whitespace(source: &str, pos: usize) -> usize {
    let bytes = source.as_bytes();
    let mut p = pos;
    while p > 0 {
        let c = bytes[p - 1];
        if c == b' ' || c == b'\t' || c == b'\n' || c == b'\r' {
            p -= 1;
        } else {
            break;
        }
    }
    p
}

/// Find the matching open bracket for the close bracket at `close_pos`.
fn find_matching_open(source: &str, close_pos: usize, open: char, close: char) -> Option<usize> {
    let bytes = source.as_bytes();
    if bytes.get(close_pos) != Some(&(close as u8)) {
        return None;
    }
    let mut depth = 0i32;
    // Iterate backward.
    let prefix = &source[..=close_pos];
    for (byte_idx, ch) in prefix.char_indices().rev() {
        if ch == close {
            depth += 1;
        } else if ch == open {
            depth -= 1;
            if depth == 0 {
                return Some(byte_idx);
            }
        }
    }
    None
}

/// Find a `[numthreads(...)]` attribute in `source[start..end]`.
fn find_numthreads_in_range(
    source: &str,
    start: usize,
    end: usize,
) -> Option<((u32, u32, u32), Range<usize>)> {
    let slice = &source[start..end];
    let needle = "numthreads";
    let rel_pos = slice.find(needle)?;
    // Find the opening `[` before this position.
    let bracket_pos = source[start..start + rel_pos]
        .rfind('[')
        .map(|i| start + i)?;
    let (inner, close_pos) = scan_bracket_block(source, bracket_pos)?;
    let nt = parse_numthreads(inner.trim())?;
    Some((nt, bracket_pos..close_pos))
}

/// Parse `numthreads(X, Y, Z)` from the inner content of `[numthreads(...)]`.
fn parse_numthreads(s: &str) -> Option<(u32, u32, u32)> {
    // s might be "numthreads(64, 1, 1)" or already stripped to "64, 1, 1".
    let inner = if let Some(i) = s.find('(') {
        let close = s.rfind(')')?;
        &s[i + 1..close]
    } else {
        s
    };
    let parts: Vec<&str> = inner.split(',').collect();
    if parts.len() < 3 {
        return None;
    }
    let x: u32 = parts[0].trim().parse().ok()?;
    let y: u32 = parts[1].trim().parse().ok()?;
    let z: u32 = parts[2].trim().parse().ok()?;
    Some((x, y, z))
}

