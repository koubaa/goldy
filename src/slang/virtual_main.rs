//! Source-to-source transform for Goldy virtual entry points.
//!
//! Shader authors write entry points annotated with `[goldy_compute]`,
//! `[goldy_vertex]`, or `[goldy_fragment]` using ergonomic typed parameters
//! (`Scattered<T>`, `ThreadId`, etc.).  This module transforms those into
//! standard `[shader("...")]` entry points that the Slang compiler accepts,
//! with a fixed 16-word signature mapping to the 128-byte `PushLayout`.
//!
//! # Push constant layout
//!
//! ```text
//! Words  0– 7: _bw0.._bw7  (16 × u16 bindless indices packed 2-per-word, bytes 0–31)
//! Words  8–15: _uw0.._uw7  (8 × u32 user scalar params full-precision, bytes 32–63)
//! Bytes 64–127: reserved
//! ```
//!
//! # Before / After (compute example)
//!
//! ```slang
//! // Input written by the shader author:
//! [goldy_compute]
//! [numthreads(64, 1, 1)]
//! void cs_main(TimeUniforms cfg, Scattered<uint> data, ThreadId id) {
//!     data[id.x] = data[id.x] + cfg.base;
//! }
//!
//! // Generated by this module (prepended to the source):
//! [shader("compute")]
//! [numthreads(64, 1, 1)]
//! void cs_main(uniform uint _bw0, ..., uniform uint _bw7,
//!              uniform uint _uw0, ..., uniform uint _uw7,
//!              uint3 _sv0 : SV_DispatchThreadID) {
//!     TimeUniforms cfg = goldy_broadcast<TimeUniforms>(_bw0 & 0xFFFFu);
//!     Scattered<uint> data = goldy_scattered<uint>((_bw0 >> 16u) & 0xFFFFu);
//!     ThreadId id = ThreadId(_sv0);
//!     _goldy_user_cs_main(cfg, data, id);
//! }
//! ```

