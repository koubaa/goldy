/// Modify the original source in place (applied in reverse position order).
fn apply_entry_transforms(source: &mut String, entry: &EntryDef) {
    // We must apply changes in reverse order of position to keep ranges valid.
    // Collect all (start, end, replacement) tuples and sort descending.
    let mut replacements: Vec<(usize, usize, &str)> = Vec::new();

    // 1. Remove return semantic from user fn (fragment only; goes to generated wrapper).
    if let Some(ref sr) = entry.return_semantic_range {
        replacements.push((sr.start, sr.end, ""));
    }

    // 2. Rename the function name.
    let new_fn_name = format!("_goldy_user_{}", entry.fn_name);
    replacements.push((
        entry.fn_name_range.start,
        entry.fn_name_range.end,
        // leak is fine — these strings live for the duration of compilation
        Box::leak(new_fn_name.into_boxed_str()),
    ));

    // 3. Remove [numthreads(...)] from the user function (compute only).
    //    It lives on the generated wrapper, not the user helper function.
    if let Some(ref nr) = entry.numthreads_attr_range {
        // Include any trailing whitespace/newline.
        let end = skip_whitespace_in_source(source, nr.end);
        replacements.push((nr.start, end, ""));
    }

    // 4. Remove the [goldy_*] attribute.
    {
        let end = skip_whitespace_in_source(source, entry.goldy_attr_range.end);
        replacements.push((entry.goldy_attr_range.start, end, ""));
    }

    // Sort by start position descending, apply.
    replacements.sort_by_key(|b| std::cmp::Reverse(b.0));
    for (start, end, replacement) in replacements {
        if start < source.len() && end <= source.len() && start <= end {
            source.replace_range(start..end, replacement);
        }
    }
}

/// Advance `pos` past any whitespace in `source`, stopping before non-whitespace.
fn skip_whitespace_in_source(source: &str, pos: usize) -> usize {
    let bytes = source.as_bytes();
    let mut p = pos;
    while p < bytes.len()
        && (bytes[p] == b' ' || bytes[p] == b'\t' || bytes[p] == b'\n' || bytes[p] == b'\r')
    {
        p += 1;
    }
    p
}

