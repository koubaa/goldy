/// Classification of a single parameter in a `[goldy_*]` entry point.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ParamKind {
    /// A Goldy resource handle type → becomes `uniform uint` resource slot resolved via goldy_*.
    Resource,
    /// A user-defined struct → becomes `uniform uint` resource slot resolved via goldy_broadcast.
    ///
    /// In compute shaders every unrecognised struct is a broadcast (constant buffer).
    /// In vertex/fragment shaders every unrecognised struct *except the last* is a broadcast;
    /// the last one is the stage input and stays as [`ParamKind::PassThrough`].
    Broadcast,
    /// A Goldy SV wrapper type → becomes an `SV_*`-annotated parameter.
    SystemValue(SvKind),
    /// A plain scalar type (uint, float, int, …) → becomes `uniform T` entry-point parameter.
    Scalar,
    /// Stage input varying / vertex-attribute struct → passed through unchanged.
    PassThrough,
}

/// The kind of system-value a `SystemValue` param maps to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SvKind {
    DispatchThreadId, // SV_DispatchThreadID  uint3
    GroupThreadId,    // SV_GroupThreadID     uint3
    GroupId,          // SV_GroupID           uint3
    VertexId,         // SV_VertexID          uint
    InstanceId,       // SV_InstanceID        uint
    IsFrontFace,      // SV_IsFrontFace       bool
}

impl SvKind {
    /// HLSL semantic name.
    fn semantic(self) -> &'static str {
        match self {
            SvKind::DispatchThreadId => "SV_DispatchThreadID",
            SvKind::GroupThreadId => "SV_GroupThreadID",
            SvKind::GroupId => "SV_GroupID",
            SvKind::VertexId => "SV_VertexID",
            SvKind::InstanceId => "SV_InstanceID",
            SvKind::IsFrontFace => "SV_IsFrontFace",
        }
    }

    /// The primitive type for the generated SV parameter.
    fn primitive(self) -> &'static str {
        match self {
            SvKind::DispatchThreadId | SvKind::GroupThreadId | SvKind::GroupId => "uint3",
            SvKind::VertexId | SvKind::InstanceId => "uint",
            SvKind::IsFrontFace => "bool",
        }
    }
}

/// A single parameter from a `[goldy_*]` entry-point signature.
#[derive(Debug, Clone)]
pub struct Param {
    /// Parameter name as written in the user source (e.g., `"data"`, `"id"`).
    pub name: String,
    /// Full type string as written (e.g., `"Scattered<uint>"`, `"ThreadId"`).
    pub ty: String,
    /// Classified kind.
    pub kind: ParamKind,
}

/// A parameter item in a `[goldy_*]` entry-point signature.
///
/// Parameters may be wrapped in preprocessor conditionals (`#ifdef`/`#else`/`#endif`)
/// directly inside the function's parameter list (as in `fine.slang`'s MSAA variants).
/// This enum represents both the simple and conditional cases.
#[derive(Debug, Clone)]
pub enum ParamItem {
    Single(Param),
    /// A `#ifdef condition … #else … #endif` block directly inside the parameter list.
    Conditional {
        condition: String,
        then_params: Vec<Param>,
        else_params: Vec<Param>,
    },
}

