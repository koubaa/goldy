/// Strip `//`-to-end-of-line comments from each line, preserving newlines so that
/// multi-line parameter lists stay structurally intact for `#ifdef` handling.
fn strip_line_comments(s: &str) -> String {
    s.lines()
        .map(|line| {
            if let Some(idx) = line.find("//") {
                &line[..idx]
            } else {
                line
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Parse a comma-separated parameter list, handling nested `<...>` brackets.
///
/// Inline `//` comments are stripped first — without this, trailing comments on
/// parameter lines become part of the next parameter's type string, producing
/// invalid generated code that causes Slang ICEs.
fn parse_params(params_str: &str) -> Vec<Param> {
    let cleaned = strip_line_comments(params_str);
    let mut params = Vec::new();
    let mut current = String::new();
    let mut depth: i32 = 0;

    for ch in cleaned.chars() {
        match ch {
            '<' | '(' | '[' => {
                depth += 1;
                current.push(ch);
            }
            '>' | ')' | ']' => {
                depth -= 1;
                current.push(ch);
            }
            ',' if depth == 0 => {
                let trimmed = current.trim();
                if !trimmed.is_empty() {
                    if let Some(p) = parse_single_param(trimmed) {
                        params.push(p);
                    }
                }
                current.clear();
            }
            _ => current.push(ch),
        }
    }

    let trimmed = current.trim();
    if !trimmed.is_empty() {
        if let Some(p) = parse_single_param(trimmed) {
            params.push(p);
        }
    }

    params
}

/// Parse a parameter list that may contain `#ifdef`/`#else`/`#endif` directives.
///
/// For simple lists with no preprocessor conditionals, delegates to [`parse_params`].
/// For lists that contain `#ifdef`, segments the text at preprocessor boundaries and
/// returns [`ParamItem::Conditional`] items wrapping the alternative parameter sets.
fn parse_params_items(params_str: &str) -> Vec<ParamItem> {
    if !params_str.contains("#ifdef") {
        return parse_params(params_str).into_iter().map(ParamItem::Single).collect();
    }

    let mut items: Vec<ParamItem> = Vec::new();
    let mut outer_text = String::new();

    let mut in_ifdef = false;
    let mut condition = String::new();
    let mut then_text = String::new();
    let mut else_text = String::new();
    let mut in_else = false;

    for line in params_str.lines() {
        let trimmed = line.trim();

        // Skip blank lines and `//` comment lines: they may contain commas or other
        // punctuation that would confuse the comma-splitting in parse_params.
        if trimmed.is_empty() || trimmed.starts_with("//") {
            continue;
        }

        if let Some(rest) = trimmed.strip_prefix("#ifdef ") {
            if !in_ifdef {
                // Flush accumulated outer text as regular params.
                for p in parse_params(&outer_text) {
                    items.push(ParamItem::Single(p));
                }
                outer_text.clear();
                condition = rest.trim().to_string();
                then_text.clear();
                else_text.clear();
                in_else = false;
                in_ifdef = true;
            } else {
                // Nested #ifdef: not supported; treat line as literal text.
                if in_else {
                    else_text.push_str(line);
                    else_text.push('\n');
                } else {
                    then_text.push_str(line);
                    then_text.push('\n');
                }
            }
        } else if trimmed == "#else" && in_ifdef {
            in_else = true;
        } else if trimmed == "#endif" && in_ifdef {
            let then_params = parse_params(&then_text);
            let else_params = parse_params(&else_text);
            items.push(ParamItem::Conditional {
                condition: std::mem::take(&mut condition),
                then_params,
                else_params,
            });
            in_ifdef = false;
            in_else = false;
            then_text.clear();
            else_text.clear();
        } else if in_ifdef {
            if in_else {
                else_text.push_str(line);
                else_text.push('\n');
            } else {
                then_text.push_str(line);
                then_text.push('\n');
            }
        } else {
            outer_text.push_str(line);
            outer_text.push('\n');
        }
    }

    // Flush any remaining outer text.
    for p in parse_params(&outer_text) {
        items.push(ParamItem::Single(p));
    }

    items
}

/// Parse a single `type name` parameter.
fn parse_single_param(s: &str) -> Option<Param> {
    let s = s.trim();
    if s.is_empty() {
        return None;
    }

    // Skip `uniform` keyword if present (old-style params in shaders that mix styles).
    let s = if let Some(rest) = s.strip_prefix("uniform") {
        rest.trim_start()
    } else {
        s
    };

    // Find the split point between type and name: the last "whitespace gap"
    // that is not inside angle brackets or parentheses.
    let mut last_space: Option<usize> = None;
    let mut depth: i32 = 0;
    let chars: Vec<(usize, char)> = s.char_indices().collect();
    for (byte_pos, ch) in &chars {
        match ch {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ' ' | '\t' | '\n' | '\r' if depth == 0 => {
                last_space = Some(*byte_pos);
            }
            _ => {}
        }
    }

    let (ty_str, name) = if let Some(sp) = last_space {
        let ty = s[..sp].trim();
        let name = s[sp + 1..].trim();
        // If name contains spaces it likely has a : SV_ annotation (old-style param).
        // Strip the annotation: `id : SV_DispatchThreadID` → name = "id".
        let name = name.split(':').next().unwrap_or(name).trim();
        (ty.to_string(), name.to_string())
    } else {
        // No space — probably just a type with no name (shouldn't happen normally).
        (s.to_string(), String::new())
    };

    let kind = classify_type(&ty_str);
    Some(Param { name, ty: ty_str, kind })
}

/// Build the RHS initialiser expression for a resource parameter.
///
/// Resource type aliases (`Scattered<T>`, `BufRO<T>`, etc.) are plain typealiases
/// for the underlying buffer/texture handle types. The generated wrapper calls the
/// corresponding `goldy_*` free function to resolve the resource slot index to
/// a live handle. Broadcast (constant-buffer) params are handled by their own
/// `ParamKind::Broadcast` arm — only handle types appear here.
fn resource_init_expr(ty: &str, slot_var: &str) -> String {
    let ty = ty.trim();

    // Extract inner type T from Wrapper<T> for generic free-function calls.
    fn inner(ty: &str, prefix: &str) -> Option<String> {
        if ty.starts_with(prefix) && ty.ends_with('>') {
            Some(ty[prefix.len()..ty.len() - 1].to_string())
        } else {
            None
        }
    }

    if let Some(t) = inner(ty, "Scattered<") {
        return format!("goldy_scattered<{}>({})", t, slot_var);
    }
    if let Some(t) = inner(ty, "BufRO<") {
        return format!("goldy_buf_ro<{}>({})", t, slot_var);
    }
    if let Some(t) = inner(ty, "Interpolated<") {
        return format!("goldy_interpolated<{}>({})", t, slot_var);
    }
    if let Some(t) = inner(ty, "DirectSpatial<") {
        return format!("goldy_direct_spatial<{}>({})", t, slot_var);
    }
    if ty == "ByteAddress" {
        return format!("goldy_byte_address({})", slot_var);
    }
    if ty == "Filter" {
        return format!("goldy_filter({})", slot_var);
    }
    if ty == "Accel" {
        return format!("goldy_accel({})", slot_var);
    }
    // Unrecognised resource type: fall back to calling __init(slot).
    format!("{}({})", ty, slot_var)
}

/// Post-pass: reclassify `PassThrough` parameters as `Broadcast` based on stage.
///
/// After initial classification, every unrecognised struct lands in `PassThrough`.
/// This pass promotes those to `Broadcast` (constant-buffer fetch) except for the
/// stage-input parameter in vertex/fragment shaders, which genuinely passes through.
///
/// Rule:
/// - Compute: ALL `PassThrough` → `Broadcast` (no stage inputs exist in compute).
/// - Vertex/Fragment: all `PassThrough` except the last `Single(PassThrough)` → `Broadcast`.
///   The last one is the vertex attribute struct or fragment varying.
fn reclassify_passthrough(params: &mut [ParamItem], stage: Stage) {
    // In vertex/fragment, the last Single(PassThrough) is the stage input — keep it,
    // but ONLY if it's truly the final parameter.  When system-value params (VertexId,
    // InstanceId, etc.) follow the last PassThrough, there is no stage-input struct
    // and all PassThroughs are broadcasts.
    let preserve_idx: Option<usize> = match stage {
        Stage::Vertex | Stage::Fragment => {
            let last_pt = params
                .iter()
                .rposition(|item| matches!(item, ParamItem::Single(p) if p.kind == ParamKind::PassThrough));
            if let Some(idx) = last_pt {
                let has_sv_after = params[idx + 1..]
                    .iter()
                    .any(|item| matches!(item, ParamItem::Single(p) if matches!(p.kind, ParamKind::SystemValue(_))));
                if has_sv_after {
                    None
                } else {
                    Some(idx)
                }
            } else {
                None
            }
        }
        Stage::Compute => None,
    };

    for (i, item) in params.iter_mut().enumerate() {
        match item {
            ParamItem::Single(p) if p.kind == ParamKind::PassThrough && Some(i) != preserve_idx => {
                p.kind = ParamKind::Broadcast;
            }
            ParamItem::Conditional {
                then_params,
                else_params,
                ..
            } => {
                // Conditional blocks never contain stage inputs — all PassThrough → Broadcast.
                for p in then_params.iter_mut().chain(else_params.iter_mut()) {
                    if p.kind == ParamKind::PassThrough {
                        p.kind = ParamKind::Broadcast;
                    }
                }
            }
            _ => {}
        }
    }
}

/// Classify a Slang type string into a `ParamKind`.
fn classify_type(ty: &str) -> ParamKind {
    let ty = ty.trim();

    // Resource wrappers (generic).
    if ty.starts_with("Scattered<") {
        return ParamKind::Resource;
    }
    if ty.starts_with("BufRO<") {
        return ParamKind::Resource;
    }
    if ty.starts_with("Interpolated<") {
        return ParamKind::Resource;
    }
    if ty.starts_with("DirectSpatial<") {
        return ParamKind::Resource;
    }

    // Resource wrappers (non-generic).
    if ty == "ByteAddress" {
        return ParamKind::Resource;
    }
    if ty == "Filter" {
        return ParamKind::Resource;
    }
    if ty == "Accel" {
        return ParamKind::Resource;
    }

    // System-value types.
    if ty == "ThreadId" {
        return ParamKind::SystemValue(SvKind::DispatchThreadId);
    }
    if ty == "GroupThreadId" {
        return ParamKind::SystemValue(SvKind::GroupThreadId);
    }
    if ty == "GroupId" {
        return ParamKind::SystemValue(SvKind::GroupId);
    }
    if ty == "VertexId" {
        return ParamKind::SystemValue(SvKind::VertexId);
    }
    if ty == "InstanceId" {
        return ParamKind::SystemValue(SvKind::InstanceId);
    }
    if ty == "IsFrontFace" {
        return ParamKind::SystemValue(SvKind::IsFrontFace);
    }

    // Plain scalars → uniform entry-point parameters.
    if matches!(
        ty,
        "uint"
            | "int"
            | "float"
            | "bool"
            | "half"
            | "double"
            | "uint2"
            | "uint3"
            | "uint4"
            | "int2"
            | "int3"
            | "int4"
            | "float2"
            | "float3"
            | "float4"
    ) {
        return ParamKind::Scalar;
    }

    // Everything else is a pass-through (varying input structs, etc.).
    ParamKind::PassThrough
}

