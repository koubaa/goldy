/// Qualified Slang opcode name for a stable name, or `None` for opcodes newer than this table.
pub(super) fn opcode_name(stable: u32) -> Option<&'static str> {
    STABLE_NAMES
        .binary_search_by_key(&stable, |(n, _)| *n)
        .ok()
        .map(|i| STABLE_NAMES[i].1)
}
